const assert=require('node:assert/strict');
const {TASKS,summarize,overdue,daysUntil}=require('./data.js');
assert.deepEqual(summarize(TASKS),{open:8,overdue:3,due:2,onTime:75,closed:4});
assert.equal(TASKS.filter(overdue).length,3);
assert.equal(overdue(TASKS.find(t=>t.id==='OP-110')),false,'Completed late work must not remain overdue');
assert.equal(summarize([]).onTime,null,'No completed records must not show 0%');
const next30=TASKS.filter(t=>daysUntil(t)>=0&&daysUntil(t)<=30);
assert.equal(next30.length,3);assert.equal(summarize(next30).overdue,0);
assert.equal(summarize(TASKS.filter(t=>t.team==='People')).onTime,100);
assert.equal(new Set(TASKS.map(t=>t.id)).size,TASKS.length);
console.log('Passed: totals, overdue rules, empty denominator, date range, team slice, and unique IDs.');
const {filterRequests,sortRequests,scheduleState,requestsCsv}=require('./data.js');
assert.equal(filterRequests(TASKS,{query:'  aLeX  '}).length,2);
assert.deepEqual(filterRequests(TASKS,{team:'People',status:'overdue'}).map(t=>t.id),['OP-101']);
assert.deepEqual(filterRequests(TASKS,{window:'30'}).map(t=>t.id),['OP-104','OP-105','OP-106']);
assert.equal(filterRequests(TASKS,{query:'no such request'}).length,0);
assert.deepEqual(sortRequests(TASKS).slice(0,3).map(t=>t.id),['OP-101','OP-102','OP-103']);
assert.equal(sortRequests(TASKS,'due')[0].id,'OP-109');
assert.equal(sortRequests(TASKS,'priority')[0].priority,'High');
assert.equal(TASKS[0].id,'OP-101','Sorting must not mutate source data');
assert.equal(scheduleState(TASKS.find(t=>t.id==='OP-110')),'Completed late');
assert.equal(overdue({...TASKS[0],due:'2026-11-11'}),false,'Due today is not overdue');
assert.equal(summarize([{...TASKS[0],due:'2026-11-18'}]).due,1);
assert.equal(summarize([{...TASKS[0],due:'2026-11-19'}]).due,0);
const csv=requestsCsv([TASKS[0]]);
assert.match(csv,/"Waiting on info","Overdue"/);
assert.match(csv,/"2026-11-11"/);
assert.equal(csv.split('\r\n').length,2);
assert.match(requestsCsv([{...TASKS[0],title:'A "quoted", request'}]),/"A ""quoted"", request"/);
assert.match(requestsCsv([{...TASKS[0],title:'=SUM(A1)'}]),/"'=SUM\(A1\)"/);
console.log('Passed: combined filters, search, attention sorting, date boundaries, CSV parity, escaping, and formula neutralization.');
assert.deepEqual(filterRequests(TASKS,{status:'due'}).map(t=>t.id),['OP-104','OP-105']);
assert.equal(filterRequests(TASKS,{status:'open'}).length,8);
assert.equal(filterRequests(TASKS,{status:'complete'}).length,4);
assert.equal(filterRequests(TASKS,{team:'People',status:'due'}).length,1);
assert.equal(filterRequests(TASKS,{status:'invalid'}).length,0);
assert.equal(filterRequests([{...TASKS[0],due:'2026-11-11'}],{status:'due'}).length,1);
assert.equal(filterRequests([{...TASKS[0],due:'2026-11-18'}],{status:'due'}).length,1);
assert.equal(filterRequests([{...TASKS[0],due:'2026-11-19'}],{status:'due'}).length,0);
assert.equal(filterRequests([{...TASKS[0],due:'2026-11-10'}],{status:'due'}).length,0);
console.log('Passed: KPI drilldown counts, team scope, and seven day boundaries.');
